// Shared build logic for the per-Minecraft-version NeoForge adapter modules.
//
// Compiles the shared Mojang-mapped sources in platforms/fabric-common together with the thin
// NeoForge loader bridge in platforms/neoforge-loader, then packages both a standalone NeoForge
// jar and a relocated universalAdapterJar for the universal distribution jar.
import org.gradle.api.tasks.SourceSetContainer
import org.gradle.language.jvm.tasks.ProcessResources

val adapterTag = extra["neoforgeAdapterTag"] as String
val minecraftRange = extra["neoforgeMinecraftRange"] as String
val neoforgeRange = extra["neoforgeLoaderRange"] as String
val javaVersion = extra["neoforgeJavaVersion"] as Int
val relocatedPackage = "com.griefprevention.neoforge.$adapterTag"
val standaloneMixinConfig = "griefprevention3d-neoforge.mixins.json"
val universalMixinConfig = "griefprevention3d-neoforge-$adapterTag.mixins.json"

val commonDir = rootProject.file("platforms/fabric-common")
val neoforgeLoaderDir = rootProject.file("platforms/neoforge-loader")
val mixinSource = commonDir.resolve("src/main/resources/griefprevention3d.mixins.json")

group = rootProject.group
version = rootProject.version

repositories {
    mavenCentral()
    maven("https://maven.neoforged.net/releases/")
    maven("https://api.modrinth.com/maven")
}

fun rewriteMixinConfig(targetPackage: String): String {
    val original = mixinSource.readText()
    val updated = original
        .replace(
            "\"package\": \"com.griefprevention.fabric.mixin\"",
            "\"package\": \"$targetPackage\""
        )
        .replace(
            "\"plugin\": \"com.griefprevention.fabric.bootstrap.AdapterMixinGate\"",
            "\"plugin\": \"com.griefprevention.neoforge.bootstrap.NeoForgeAdapterMixinGate\""
        )
    if (updated == original || !updated.contains(targetPackage) || !updated.contains("NeoForgeAdapterMixinGate")) {
        throw GradleException("Could not generate NeoForge mixin config from $mixinSource.")
    }
    return updated
}

val generateNeoForgeAdapterIndex = tasks.register("generateNeoForgeAdapterIndex") {
    val output = layout.buildDirectory.dir("generated/neoforge-adapter-index")
    inputs.property("tag", adapterTag)
    inputs.property("minecraftRange", minecraftRange)
    outputs.dir(output)

    doLast {
        val index = output.get().file("META-INF/griefprevention3d/neoforge-adapters.properties").asFile
        index.parentFile.mkdirs()
        index.writeText(
            """
            |# Generated by the build: the NeoForge adapter in this module jar and the releases it serves.
            |adapters=$adapterTag
            |adapter.$adapterTag.minecraft=$minecraftRange
            |adapter.$adapterTag.entrypoint=com.griefprevention.fabric.GriefPreventionNeoForge
            |adapter.$adapterTag.mixins=com.griefprevention.fabric.mixin
            |""".trimMargin()
        )
    }
}

val generateStandaloneMixinConfig = tasks.register("generateStandaloneMixinConfig") {
    val output = layout.buildDirectory.dir("generated/neoforge-standalone-mixins")
    inputs.file(mixinSource)
    outputs.dir(output)

    doLast {
        val file = output.get().file(standaloneMixinConfig).asFile
        file.parentFile.mkdirs()
        file.writeText(rewriteMixinConfig("com.griefprevention.fabric.mixin"))
    }
}

val relocatedMixinConfig = tasks.register("relocatedMixinConfig") {
    val output = layout.buildDirectory.dir("generated/neoforge-universal-mixins")
    inputs.file(mixinSource)
    inputs.property("relocatedPackage", relocatedPackage)
    outputs.dir(output)

    doLast {
        val file = output.get().file(universalMixinConfig).asFile
        file.parentFile.mkdirs()
        file.writeText(rewriteMixinConfig("$relocatedPackage.mixin"))
    }
}

the<SourceSetContainer>().apply {
    named("main") {
        java.srcDir(commonDir.resolve("src/main/java"))
        java.srcDir(neoforgeLoaderDir.resolve("src/main/java"))
        resources.srcDir(neoforgeLoaderDir.resolve("src/main/resources"))
        resources.srcDir(generateNeoForgeAdapterIndex)
        resources.srcDir(generateStandaloneMixinConfig)
    }
    named("test") {
        java.srcDir(commonDir.resolve("src/test/java"))
        java.srcDir(neoforgeLoaderDir.resolve("src/test/java"))
    }
}

tasks.named<ProcessResources>("processResources") {
    inputs.property("version", project.version.toString())
    inputs.property("minecraftRange", minecraftRange)
    inputs.property("neoforgeRange", neoforgeRange)
    inputs.property("standaloneMixinConfig", standaloneMixinConfig)
    filesMatching("META-INF/neoforge.mods.toml") {
        expand(
            "version" to project.version.toString(),
            "minecraftRange" to minecraftRange,
            "neoforgeRange" to neoforgeRange,
            "mixinsBlock" to "[[mixins]]\nconfig=\"$standaloneMixinConfig\""
        )
    }
}

